import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

describe('native Excalidraw shell', () => {
  it('does not contain a custom sidebar and leaves canvas actions to Excalidraw', () => {
    const app = readFileSync(resolve(process.cwd(), 'src/App.vue'), 'utf8');
    const quickToolbar = readFileSync(resolve(process.cwd(), 'src/components/LibraryQuickToolbar.vue'), 'utf8');
    const deleteDialog = readFileSync(resolve(process.cwd(), 'src/components/DeleteDrawingDialog.vue'), 'utf8');
    const adapter = readFileSync(resolve(process.cwd(), 'src/adapters/excalidraw-react.ts'), 'utf8');
    const css = readFileSync(resolve(process.cwd(), 'src/styles/host.css'), 'utf8');
    expect(app).not.toContain('SidebarNav');
    expect(app).not.toContain('DrawingDirectoryPanel');
    expect(adapter).not.toContain('UIOptions');
    expect(adapter).not.toContain('saveAsImage: false');
    expect(adapter).not.toContain('loadScene: false');
    expect(adapter).toContain('renderTopRightUI');
    expect(adapter).toContain('treasure-library-trigger');
    expect(adapter).toContain('libraryIcon');
    expect(adapter).toContain('MainMenu');
    expect(adapter).not.toContain('MainMenu.DefaultItems.Socials');
    expect(adapter).toContain("'绘图目录'");
    expect(adapter).toContain('onDrawingOpen');
    expect(adapter).toContain('onDrawingNew');
    expect(adapter).toContain('onMindMapImport');
    expect(adapter).toContain('导入思维导图');
    expect(adapter).toContain('onDrawingSave');
    expect(adapter).toContain('onDrawingClose');
    expect(adapter).toContain('onDrawingDelete');
    expect(app).toContain('@drawing-open="openDrawing"');
    expect(app).toContain('@drawing-delete="requestDeleteDrawing"');
    expect(app).toContain('<LibraryQuickToolbar :items="libraryItems" @insert="insertLibraryItem" />');
    expect(app).toContain('@open-canvas-library="openCanvasLibrary"');
    expect(app).toContain('@drawing-new="requestNewDrawing"');
    expect(app).toContain('@mind-map-import="importMindMap"');
    expect(app).toContain('@drawing-save="saveDrawing"');
    expect(app).toContain('@drawing-close="closeDrawing"');
    expect(app).not.toContain('DirectoryPanel');
    expect(app).not.toContain('drawerTab');
    expect(app).not.toContain('>绘图目录</button>');
    expect(app).toContain('side-panel--drawer');
    expect(css).toContain('.sidebar-trigger__label-element:has(input[aria-label*="Libr"])');
    expect(css).toContain('.default-sidebar .sidebar-triggers > .sidebar-tab-trigger:nth-child(2)');
    expect(css).toContain('.default-sidebar .sidebar-triggers > .sidebar-tab-trigger:nth-child(2)');
    expect(css).toContain('.treasure-drawing-file-delete');
    expect(css).toContain('.treasure-library-trigger svg');
    expect(css).toContain('.panel__header-actions');
    expect(css).toContain('.library-quick-toolbar');
    expect(css).toContain('.library-quick-toolbar { position: absolute; top: 68px; right: 12px;');
    expect(css).not.toContain('.library-quick-toolbar { position: absolute; top: 68px; left: 12px;');
    expect(css).toContain('width: var(--quick-width, 44px)');
    expect(css).toContain('max-height: min(550px');
    expect(quickToolbar).toContain(':style="toolbarStyle"');
    expect(quickToolbar).toContain("'--quick-expanded-columns'");
    expect(css).toContain('grid-template-rows: repeat(13, 36px)');
    expect(css).toContain('.library-quick-toolbar--expanded { direction: rtl;');
    expect(css).toContain('isolation: isolate');
    expect(css).toContain('.side-panel--drawer { position: absolute; z-index: 1000;');
    expect(css).toContain('.drawer-backdrop { position: absolute;');
    expect(css).toContain('.drawer-toolbar { display: flex;');
    expect(css).toContain('.drawer-close { display: grid;');
    expect(css).toContain('.library-card__description { display: -webkit-box;');
    expect(css).toContain('.modal-backdrop { position: fixed; inset: 0; z-index: 1100;');
    expect(deleteDialog).toContain('data-prevent-outside-click');
  });
});
